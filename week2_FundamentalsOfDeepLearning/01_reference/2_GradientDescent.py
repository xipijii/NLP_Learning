# ✍️2. 确定损失函数
def loss(y_pred, y_true):
    return (y_pred - y_true) ** 2
    # ✍️为何加平方？如果没有平方，损失函数没有极小值，不能使用梯度下降理论了，所以不是所有函数都能作为损失函数


# ✍️3. 权重随机初始化
