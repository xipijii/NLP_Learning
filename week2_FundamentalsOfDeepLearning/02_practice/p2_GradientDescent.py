# 1. 确定模型并初始化权重
w0, w1, w2, w3 = 0, 0, 0, 0
def function(x):
    return w0 * x ** 3 + w1 * x ** 2 + w2 * x + w3

# ➕2. 确定损失函数‼️
def loss(y_pre, y):  # 顺序 y_pre, y
    return (y_pre - y) ** 2

# 参数设置
batch_size = 10
lr = 0.01

# 执行训练 (epoch轮)(样本数量为100)
for epoch in range(10000):
    # loss = 0  # ❓每一轮训练 出一个loss
    epoch_loss = 0  # ❓每一轮训练 出一个loss
    grad_w0, grad_w1, grad_w2, grad_w3 = 0, 0, 0, 0
    count = 0
    for x, y in zip(X, Y):
        count += 1
        # 3. 计算预测值
        y_pre = function(x)
        # 4. 计算loss函数
        epoch_loss += loss(y_pre, y)
        # 5. 根据loss计算模型权重的梯度(在loss函数中对每个自变量求导)
                                                                # grad_w0 += - 2 * (y - y_pre) * x ** 3 # 错误
                                                                # grad_w1 += - 2 * (y - y_pre) * x ** 2
                                                                # grad_w2 += - 2 * (y - y_pre) * x
                                                                # grad_w3 += - 2 * (y - y_pre)
        grad_w0 += 2 * (y_pre - y) * x ** 3
        grad_w1 += 2 * (y_pre - y) * x ** 2
        grad_w2 += 2 * (y_pre - y) * x
        grad_w3 += 2 * (y_pre - y)
        print(grad_w0, grad_w1, grad_w2, grad_w3)
        #   每一个batch调整一次权重
        if count == batch_size:
            # 6. 使用梯度和学习率，根据优化器调整模型权重
            w0 = w0 - lr * grad_w0/batch_size
            w1 = w1 - lr * grad_w1/batch_size
            w2 = w2 - lr * grad_w2/batch_size
            w3 = w3 - lr * grad_w3/batch_size
            # 重置梯度
            grad_w0, grad_w1, grad_w2, grad_w3 = 0, 0, 0, 0
            count = 0

    epoch_loss = epoch_loss/len(X)
    print(f"第{epoch}轮的loss值：{epoch_loss}")
    if epoch_loss < 0.00001:
        break

print(f"训练后的权重为：w0={w0}, w1={w1}, w2={w2}, w3={w3}")


